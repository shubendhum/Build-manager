BY_KEY = {p["key"]: p for p in PHASES}
ITEM_COUNT = sum(len(p["items"]) for p in PHASES)


def items_for(phase_key: str) -> list:
    phase = BY_KEY.get(phase_key)
    return phase["items"] if phase else []


def find(action_key: str) -> Optional[tuple]:
    """Resolve "phase:item" to the phase and item it names."""
    phase_key, _, item_key = action_key.partition(":")
    phase = BY_KEY.get(phase_key)
    if not phase:
        return None
    for item in phase["items"]:
        if item["key"] == item_key:
            return phase, item
    return None


def phase_for_step(step_n: int) -> Optional[dict]:
    """Which phase of the checklist a sequence step belongs to."""
    return next((p for p in PHASES if step_n in p["steps"]), None)


