"""The site supervisor's own checklist, phase A to O.

The 25-step sequence in build_sequence.py says what order the TRADES come in.
This says what the SUPERVISOR has to do — the permits, the consents, the checks
before something is covered up, the certificates collected on the way out. None
of it has a package or a price against it, so none of it appeared anywhere, and
it is exactly the work that stops a job when it is missed.

Written for a single-storey slab-on-ground house in Wyndham. The stamped
building-permit drawings and the inspection schedule on the permit take priority
over anything here.

Two things earn their own treatment:

  * HOLD POINTS (phases marked hold=True). Work must not proceed past these
    until the surveyor has passed the stage. They are called out separately
    rather than buried in a list of ticks.
  * LEAD TIMES (remind_days). Wyndham wants road-reserve applications 20
    business days ahead and the asset protection report within five days of
    starting. Something that has to be applied for weeks early is worth
    surfacing weeks early.

Numbering follows the supervisor's own list so an item can be quoted by number.
"""
